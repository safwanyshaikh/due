export function buildCatalog(today: string): OfferRecord[] {
  return SEED.map((s) => {
    const base = {
      ...s,
      currency: 'INR' as const,
      sourceUrls: s.sources.map((x) => x.url),
      observedAt: s.observedAt ?? OBSERVED,
      lastConfirmedAt: s.lastConfirmedAt ?? OBSERVED,
    };
    return { ...base, computedStatus: computeStatus(base, today) };
  });
}

